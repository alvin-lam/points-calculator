// Builds everything the site serves from the files in data/:
//   1. js/programs.js, the single data file the browser loads
//   2. the program pages, sitemap.xml and robots.txt (tools/build-pages.js)
// Run after any change in data/ or index.html:  node tools/build.js
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const DATA = path.join(ROOT, "data");

// Loads and checks every program file. Throws with a clear message on the
// first problem, so a bad file never reaches the site.
function loadPrograms() {
  const dir = path.join(DATA, "programs");
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".js")).sort();
  return files.map((f) => {
    const file = path.join(dir, f);
    delete require.cache[require.resolve(file)];
    const p = require(file);
    const where = "data/programs/" + f + ": ";
    const fail = (msg) => { throw new Error(where + msg); };
    if (p.id + ".js" !== f) fail("id \"" + p.id + "\" must match the file name");
    if (!/^\d{4}-(0[1-9]|1[0-2])$/.test(p.reviewed || "")) fail("reviewed must look like 2026-11");
    if (!p.rules || !p.rules.name) fail("rules.name is missing");
    const checkMeta = (m, label) => {
      if (!m) fail(label + " has no code, color or source");
      if (!/^#[0-9A-Fa-f]{6}$/.test(m.color || "")) fail(label + " needs a color like #005DAA");
      if (!/^https:\/\//.test(m.source || "")) fail(label + " needs a source link starting with https://");
      if (m.code !== undefined && !/^[A-Z0-9]{2}$/.test(m.code)) fail(label + " code must be two letters or digits");
    };
    if (p.rules.airlines) {
      const ids = p.rules.airlines.map((a) => a.id);
      const metaIds = Object.keys(p.airlines || {});
      // An airline can rely on the program's own code, color or source.
      ids.forEach((id) => checkMeta(Object.assign({ code: p.code, color: p.color, source: p.source }, (p.airlines || {})[id]), "airline " + id));
      metaIds.forEach((id) => { if (!ids.includes(id)) fail("airlines." + id + " is not in rules.airlines"); });
    } else {
      checkMeta(p, "the program");
    }
    (p.examples || []).forEach((e) => {
      if (!e.name || !e.input || typeof e.expect !== "number") fail("each example needs name, input and expect");
      if (e.airline && !(p.rules.airlines || []).some((a) => a.id === e.airline)) fail("example \"" + e.name + "\" names an unknown airline");
    });
    return p;
  });
}

// The browser data, keyed the way the app reads it.
function compile() {
  const programs = loadPrograms();
  const PROGRAMS = {}, BRAND_COLORS = {}, AIRLINE_CODES = {}, SOURCES = {}, REVIEWED = {};
  programs.forEach((p) => {
    PROGRAMS[p.id] = structuredClone(p.rules);
    const metas = p.rules.airlines
      ? p.rules.airlines.map((a) => [p.id + ":" + a.id, p.airlines[a.id]])
      : [[p.id, p]];
    // A group program's own values cover airlines without their own.
    if (p.rules.airlines) {
      if (p.color) BRAND_COLORS[p.id] = p.color;
      if (p.source) SOURCES[p.id] = p.source;
      if (p.code) AIRLINE_CODES[p.id] = p.code;
    }
    metas.forEach(([key, m]) => {
      m = m || {};
      if (m.color) BRAND_COLORS[key] = m.color;
      if (m.source) SOURCES[key] = m.source;
      if (m.code) AIRLINE_CODES[key] = m.code;
      // Stored as YYYY-MM; the page shows it in the visitor's language.
      REVIEWED[key] = p.reviewed;
    });
  });
  require(path.join(DATA, "alliances.js"))(PROGRAMS);
  const COUNTRIES = require(path.join(DATA, "countries.js"));
  return { programs, PROGRAMS, COUNTRIES, BRAND_COLORS, AIRLINE_CODES, SOURCES, REVIEWED };
}

// JSON, except that Infinity (an open-ended tier) is kept as Infinity.
function toJs(v) {
  const MARK = "\u0000Infinity\u0000";
  return JSON.stringify(v, (k, x) => (x === Infinity ? MARK : x)).split(JSON.stringify(MARK)).join("Infinity");
}

function render(d) {
  const obj = (o) => "{\n" + Object.entries(o).map(([k, v]) => "  " + JSON.stringify(k) + ": " + toJs(v)).join(",\n") + "\n}";
  const arr = (a) => "[\n" + a.map((v) => "  " + toJs(v)).join(",\n") + "\n]";
  return [
    "/* Generated by tools/build.js from the files in data/. Do not edit this",
    "   file by hand: change data/programs/<program>.js and run the build. */",
    "window.PROGRAMS = " + obj(d.PROGRAMS) + ";",
    "window.COUNTRIES = " + arr(d.COUNTRIES) + ";",
    "window.BRAND_COLORS = " + obj(d.BRAND_COLORS) + ";",
    "window.AIRLINE_CODES = " + obj(d.AIRLINE_CODES) + ";",
    "window.SOURCES = " + obj(d.SOURCES) + ";",
    "window.REVIEWED = " + obj(d.REVIEWED) + ";",
    ""
  ].join("\n");
}

module.exports = { compile, render };

if (require.main === module) {
  const d = compile();
  fs.writeFileSync(path.join(ROOT, "docs/js/programs.js"), render(d));
  console.log("Wrote js/programs.js from " + d.programs.length + " program files.");
  require("./build-pages.js").main();
}
